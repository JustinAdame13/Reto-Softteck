-- =====================================================================
-- V1: Esquema inicial - Tienda Inteligente para Retail
-- PostgreSQL. Los ENUM se guardan como VARCHAR + CHECK para que JPA los
-- mapee directo con @Enumerated(EnumType.STRING).
-- Montos: NUMERIC(12,2). Ids: BIGINT IDENTITY (GenerationType.IDENTITY).
-- =====================================================================

-- ---------------------------------------------------------------------
-- 1. configuracion (una sola fila, id fijo = 1)
-- ---------------------------------------------------------------------
CREATE TABLE configuracion (
    id                               SMALLINT      PRIMARY KEY DEFAULT 1,
    nombre_sucursal                  VARCHAR(100)  NOT NULL,
    zona                             VARCHAR(100),
    tamano                           VARCHAR(10)   NOT NULL,
    hora_apertura                    TIME          NOT NULL,
    hora_cierre                      TIME          NOT NULL,
    ia_habilitada                    BOOLEAN       NOT NULL DEFAULT FALSE,
    margen_minimo_promo              NUMERIC(5,4)  NOT NULL,  -- fraccion: 0.10 = 10 %
    descuento_maximo                 NUMERIC(5,2)  NOT NULL,  -- porcentaje: 30 = 30 %
    meses_historico                  INT           NOT NULL,
    transacciones_por_empleado_hora  INT           NOT NULL,

    CONSTRAINT ck_configuracion_unica      CHECK (id = 1),
    CONSTRAINT ck_configuracion_tamano     CHECK (tamano IN ('PEQUENA', 'MEDIANA', 'GRANDE')),
    CONSTRAINT ck_configuracion_horario    CHECK (hora_apertura < hora_cierre),
    CONSTRAINT ck_configuracion_margen     CHECK (margen_minimo_promo >= 0 AND margen_minimo_promo <= 1),
    CONSTRAINT ck_configuracion_descuento  CHECK (descuento_maximo BETWEEN 0 AND 100),
    CONSTRAINT ck_configuracion_meses      CHECK (meses_historico >= 1),
    CONSTRAINT ck_configuracion_tx         CHECK (transacciones_por_empleado_hora >= 1)
);

-- ---------------------------------------------------------------------
-- 2. productos
-- ---------------------------------------------------------------------
CREATE TABLE productos (
    id               BIGINT        GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sku              VARCHAR(50)   NOT NULL,
    nombre           VARCHAR(150)  NOT NULL,
    categoria        VARCHAR(80)   NOT NULL,
    precio_venta     NUMERIC(12,2) NOT NULL,
    costo            NUMERIC(12,2) NOT NULL,
    stock_actual     INT           NOT NULL DEFAULT 0,
    stock_minimo     INT           NOT NULL DEFAULT 0,
    stock_maximo     INT,
    lead_time_dias   INT           NOT NULL DEFAULT 1,
    es_perecedero    BOOLEAN       NOT NULL DEFAULT FALSE,
    vida_util_dias   INT,
    activo           BOOLEAN       NOT NULL DEFAULT TRUE,

    CONSTRAINT uk_productos_sku            UNIQUE (sku),
    CONSTRAINT ck_productos_precio         CHECK (precio_venta >= 0),
    CONSTRAINT ck_productos_costo          CHECK (costo >= 0),
    CONSTRAINT ck_productos_stock_min      CHECK (stock_minimo >= 0),
    CONSTRAINT ck_productos_stock_max      CHECK (stock_maximo IS NULL OR stock_maximo >= stock_minimo),
    CONSTRAINT ck_productos_lead_time      CHECK (lead_time_dias >= 0),
    CONSTRAINT ck_productos_perecedero     CHECK (es_perecedero = FALSE OR vida_util_dias IS NOT NULL),
    CONSTRAINT ck_productos_vida_util      CHECK (vida_util_dias IS NULL OR vida_util_dias > 0)
);

CREATE INDEX ix_productos_categoria ON productos (categoria);

-- ---------------------------------------------------------------------
-- 5. empleados (antes de ventas, porque ventas la referencia)
-- ---------------------------------------------------------------------
CREATE TABLE empleados (
    id                BIGINT        GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre            VARCHAR(120)  NOT NULL,
    rol               VARCHAR(10)   NOT NULL,
    costo_hora        NUMERIC(10,2) NOT NULL,
    horas_max_semana  INT           NOT NULL DEFAULT 48,
    activo            BOOLEAN       NOT NULL DEFAULT TRUE,

    CONSTRAINT ck_empleados_rol    CHECK (rol IN ('CAJERO', 'PISO', 'ALMACEN', 'GERENTE')),
    CONSTRAINT ck_empleados_costo  CHECK (costo_hora >= 0),
    CONSTRAINT ck_empleados_horas  CHECK (horas_max_semana BETWEEN 1 AND 168)
);

-- ---------------------------------------------------------------------
-- 7. promociones (antes de ventas, porque ventas la referencia)
-- ---------------------------------------------------------------------
CREATE TABLE promociones (
    id                 BIGINT        GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    producto_id        BIGINT        NOT NULL,
    tipo               VARCHAR(15)   NOT NULL,
    valor              NUMERIC(12,2) NOT NULL,
    fecha_inicio       DATE          NOT NULL,
    fecha_fin          DATE          NOT NULL,
    estado             VARCHAR(12)   NOT NULL DEFAULT 'SUGERIDA',
    origen             VARCHAR(10)   NOT NULL,
    motivo             VARCHAR(15),
    explicacion        TEXT,
    ventas_esperadas   INT,
    ventas_reales      INT,
    ganancia_esperada  NUMERIC(12,2),
    creada_en          TIMESTAMP     NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT fk_promociones_producto FOREIGN KEY (producto_id) REFERENCES productos (id),
    CONSTRAINT ck_promociones_tipo     CHECK (tipo   IN ('PORCENTAJE', 'DOS_X_UNO', 'PRECIO_FIJO')),
    CONSTRAINT ck_promociones_estado   CHECK (estado IN ('SUGERIDA', 'ACTIVA', 'FINALIZADA', 'RECHAZADA')),
    CONSTRAINT ck_promociones_origen   CHECK (origen IN ('MANUAL', 'ALGORITMO', 'IA')),
    CONSTRAINT ck_promociones_motivo   CHECK (motivo IS NULL OR motivo IN ('SOBRESTOCK', 'POR_CADUCAR', 'BAJA_ROTACION', 'TEMPORADA')),
    CONSTRAINT ck_promociones_fechas   CHECK (fecha_inicio <= fecha_fin),
    CONSTRAINT ck_promociones_valor    CHECK (valor >= 0)
);

CREATE INDEX ix_promociones_producto_estado ON promociones (producto_id, estado);
CREATE INDEX ix_promociones_fechas          ON promociones (fecha_inicio, fecha_fin);

-- ---------------------------------------------------------------------
-- 3. ventas (plana: una fila por producto vendido)
-- ---------------------------------------------------------------------
CREATE TABLE ventas (
    id                  BIGINT        GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ticket              VARCHAR(30)   NOT NULL,
    fecha_hora          TIMESTAMP     NOT NULL,
    producto_id         BIGINT        NOT NULL,
    cantidad            INT           NOT NULL,
    precio_unitario     NUMERIC(12,2) NOT NULL,
    descuento_aplicado  NUMERIC(12,2) NOT NULL DEFAULT 0,
    promocion_id        BIGINT,
    empleado_id         BIGINT,

    CONSTRAINT fk_ventas_producto   FOREIGN KEY (producto_id)  REFERENCES productos (id),
    CONSTRAINT fk_ventas_promocion  FOREIGN KEY (promocion_id) REFERENCES promociones (id),
    CONSTRAINT fk_ventas_empleado   FOREIGN KEY (empleado_id)  REFERENCES empleados (id),
    CONSTRAINT ck_ventas_cantidad   CHECK (cantidad > 0),
    CONSTRAINT ck_ventas_precio     CHECK (precio_unitario >= 0),
    CONSTRAINT ck_ventas_descuento  CHECK (descuento_aplicado >= 0)
);

-- El algoritmo agrupa por producto y fecha; los records y plantillas por fecha/hora y ticket.
CREATE INDEX ix_ventas_fecha_hora         ON ventas (fecha_hora);
CREATE INDEX ix_ventas_producto_fecha     ON ventas (producto_id, fecha_hora);
CREATE INDEX ix_ventas_ticket             ON ventas (ticket);
CREATE INDEX ix_ventas_promocion          ON ventas (promocion_id) WHERE promocion_id IS NOT NULL;
CREATE INDEX ix_ventas_empleado           ON ventas (empleado_id)  WHERE empleado_id  IS NOT NULL;

-- ---------------------------------------------------------------------
-- 4. movimientos_inventario
-- cantidad llega positiva y el backend decide el signo; AJUSTE acepta negativos.
-- ---------------------------------------------------------------------
CREATE TABLE movimientos_inventario (
    id           BIGINT        GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    producto_id  BIGINT        NOT NULL,
    fecha        TIMESTAMP     NOT NULL DEFAULT CURRENT_TIMESTAMP,
    tipo         VARCHAR(12)   NOT NULL,
    cantidad     INT           NOT NULL,
    costo_total  NUMERIC(12,2) NOT NULL,
    motivo       VARCHAR(255),

    CONSTRAINT fk_movimientos_producto FOREIGN KEY (producto_id) REFERENCES productos (id),
    CONSTRAINT ck_movimientos_tipo     CHECK (tipo IN ('ENTRADA', 'MERMA', 'CADUCIDAD', 'AJUSTE', 'DEVOLUCION')),
    CONSTRAINT ck_movimientos_cantidad CHECK (cantidad <> 0 AND (tipo = 'AJUSTE' OR cantidad > 0))
);

CREATE INDEX ix_movimientos_producto_fecha ON movimientos_inventario (producto_id, fecha);
CREATE INDEX ix_movimientos_tipo_fecha     ON movimientos_inventario (tipo, fecha);

-- ---------------------------------------------------------------------
-- 6. plantillas_empleados (cuanta gente se necesita, no quien)
-- ---------------------------------------------------------------------
CREATE TABLE plantillas_empleados (
    id                  BIGINT       GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    dia_semana          SMALLINT     NOT NULL,  -- 1 = lunes ... 7 = domingo (ISO, igual que DayOfWeek)
    hora_inicio         TIME         NOT NULL,
    hora_fin            TIME         NOT NULL,
    rol                 VARCHAR(10)  NOT NULL,
    personal_requerido  INT          NOT NULL,
    origen              VARCHAR(12)  NOT NULL DEFAULT 'MANUAL',

    CONSTRAINT ck_plantillas_dia       CHECK (dia_semana BETWEEN 1 AND 7),
    CONSTRAINT ck_plantillas_horas     CHECK (hora_inicio < hora_fin),
    CONSTRAINT ck_plantillas_rol       CHECK (rol IN ('CAJERO', 'PISO', 'ALMACEN', 'GERENTE')),
    CONSTRAINT ck_plantillas_personal  CHECK (personal_requerido >= 0),
    CONSTRAINT ck_plantillas_origen    CHECK (origen IN ('MANUAL', 'RECOMENDADO'))
);

CREATE INDEX ix_plantillas_dia_rol ON plantillas_empleados (dia_semana, rol);

-- ---------------------------------------------------------------------
-- 8. prediccion_demanda
-- Una prediccion por producto + fecha + modelo: regenerar reemplaza (upsert).
-- ---------------------------------------------------------------------
CREATE TABLE prediccion_demanda (
    id                 BIGINT        GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    producto_id        BIGINT        NOT NULL,
    fecha_objetivo     DATE          NOT NULL,
    cantidad_predicha  NUMERIC(12,2) NOT NULL,
    limite_inferior    NUMERIC(12,2),
    limite_superior    NUMERIC(12,2),
    stock_recomendado  INT,
    cantidad_a_pedir   INT,
    modelo             VARCHAR(5)    NOT NULL,
    generada_en        TIMESTAMP     NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT fk_prediccion_producto FOREIGN KEY (producto_id) REFERENCES productos (id),
    CONSTRAINT uk_prediccion          UNIQUE (producto_id, fecha_objetivo, modelo),
    CONSTRAINT ck_prediccion_modelo   CHECK (modelo IN ('BASE', 'IA')),
    CONSTRAINT ck_prediccion_cantidad CHECK (cantidad_predicha >= 0),
    CONSTRAINT ck_prediccion_limites  CHECK (limite_inferior IS NULL OR limite_superior IS NULL
                                             OR limite_inferior <= limite_superior)
);

CREATE INDEX ix_prediccion_fecha ON prediccion_demanda (fecha_objetivo);

-- ---------------------------------------------------------------------
-- 9. contexto (una fila por dia)
-- ---------------------------------------------------------------------
CREATE TABLE contexto (
    id             BIGINT        GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    fecha          DATE          NOT NULL,
    es_festivo     BOOLEAN       NOT NULL DEFAULT FALSE,
    nombre_evento  VARCHAR(100),
    es_quincena    BOOLEAN       NOT NULL DEFAULT FALSE,
    temporada      VARCHAR(15)   NOT NULL DEFAULT 'NORMAL',
    clima          VARCHAR(50),
    temperatura    NUMERIC(4,1),

    CONSTRAINT uk_contexto_fecha     UNIQUE (fecha),
    CONSTRAINT ck_contexto_temporada CHECK (temporada IN ('REGRESO_CLASES', 'NAVIDAD', 'VERANO', 'NORMAL'))
);
